#!/usr/bin/env python3
"""Prepare the KernelEx 4.5.2019.24 (jumper) update for the French installer.

Inputs : maj2019/jumper/   jumper's original files (untouched)
         maj2019/src_fr/   French resources (UTF-8, Resource Hacker syntax)
Outputs: maj2019/          KernelEx-fr.dll, sheet-fr.dll, verify-fr.exe,
                           core.ini (FR descriptions + NT2K alias),
                           kexmaj.reg, api-ms-w.reg, api-ms-w-uninst.nsh

Usage (from the project root):
    python maj2019/build_maj2019.py [--rh "C:\\...\\ResourceHacker.exe"]

Script commente en francais dans le README (section 4.5.2019.24).
"""
import argparse
import re
import struct
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
JUMPER = HERE / "jumper"
SRC = HERE / "src_fr"


def write_text(path, text):
    """Windows 98 text file: cp1252 + CRLF."""
    path.write_bytes(text.replace("\r\n", "\n").replace("\n", "\r\n").encode("cp1252"))


def read_text(path):
    return path.read_bytes().decode("cp1252").replace("\r\n", "\n")


# ---------------------------------------------------------------- core.ini
DESC_FR = {
    "Base enhancements (api fixes + extensions)": "Améliorations de base (correctifs d'API + extensions)",
    "Base enhancements (disable custom heap)": "Améliorations de base (sans tas personnalisé)",
    "Minimal load help (Subsystem + KnownDLLs)": "Aide minimale au chargement (sous-système + KnownDLLs)",
    "Alias for Base enhancements (old)": "Alias de Améliorations de base (ancien)",
    "Windows 98 (First Edition)": "Windows 98 (première édition)",
    "Alias for Windows 98 SE (old)": "Alias de Windows 98 SE (ancien)",
    "Windows 2000 SP4 (standard heap)": "Windows 2000 SP4 (tas standard)",
    "Alias for Windows XP SP2 (old)": "Alias de Windows XP SP2 (ancien)",
    "Windows 10 (earlier)": "Windows 10 (premières versions)",
    "Windows 10 (later)": "Windows 10 (versions récentes)",
    "Windows 2000 SP4 (Multi-Threaded)": "Windows 2000 SP4 (multithread)",
}


def build_core_ini():
    core = read_text(JUMPER / "CORE.INI")
    for en, fr in DESC_FR.items():
        core = core.replace(f"desc={en}\n", f"desc={fr}\n")
    core = core.replace("=--- Experimental: ---", "=--- Expérimental : ---")
    core = core.replace("=--- Obsolete (change if found): ---", "=--- Obsolètes (à changer si présents) : ---")
    # NT2K is used by the 4.5.2 settings.reg and by KERNELEX.REG but missing from
    # jumper's CORE.INI: alias it to WIN2000D, as jumper's own CORE.20I does.
    assert "[NT2K]" not in core and "41=DCFG1\n" in core
    core = core.replace("41=DCFG1\n", "41=DCFG1\n42=NT2K\n", 1)
    core = core.rstrip("\n") + "\n\n[NT2K]\ninherit=WIN2000D\ndesc=Alias de Windows 2000 SP4 (ancien)\n"
    core = core.replace("*** KernelEx 4.5.2016.20e ***", "*** KernelEx 4.5.2016.20e - libelles FR ***", 1)
    write_text(HERE / "core.ini", core)


# ------------------------------------------------------------ registry files
def build_regs():
    # Per-application settings of jumper's KERNELEX.REG, without the shortcut
    # handler redirection (already done by 4.5.2) and the hard-coded InstallDir.
    reg = read_text(JUMPER / "KERNELEX.REG")
    keep = {"[HKEY_LOCAL_MACHINE\\Software\\KernelEx\\KnownDLLs]",
            "[HKEY_LOCAL_MACHINE\\Software\\KernelEx\\AppSettings\\Configs]",
            "[HKEY_LOCAL_MACHINE\\Software\\KernelEx\\AppSettings\\Flags]",
            "[HKEY_LOCAL_MACHINE\\Software\\KernelEx\\FontSignature]"}
    kept = [b.strip("\n") for b in re.split(r"\n(?=\[)", reg) if b.split("\n", 1)[0].strip() in keep]
    assert len(kept) == len(keep)
    write_text(HERE / "kexmaj.reg", "REGEDIT4\n\n" + "\n\n".join(kept) + "\n")

    # api-ms-win KnownDLLs: fix the malformed quotes of jumper's file.
    out, names = [], []
    for line in read_text(JUMPER / "API-MS-W.REG").split("\n"):
        m = re.match(r'^("API-MS-[^"]+"|"[A-Za-z]+\.dll")="([^"]*)"*$', line)
        if m:
            line = f'{m.group(1)}="{m.group(2)}"'
            names.append(m.group(1).strip('"'))
        out.append(line)
    write_text(HERE / "api-ms-w.reg", "\n".join(out).rstrip("\n") + "\n")
    key = r"System\CurrentControlSet\Control\SessionManager\KnownDLLs"
    write_text(HERE / "api-ms-w-uninst.nsh",
               "; Generated by build_maj2019.py - values written by api-ms-w.reg\n"
               + "".join(f'  DeleteRegValue HKLM "{key}" "{n}"\n' for n in names))


# ------------------------------------------------------- translated binaries
def string_table_res(rc_path):
    """Build a .res holding the STRINGTABLE of rc_path (LANG_NEUTRAL).
    Resource Hacker cannot compile "\\n" inside strings, so it is done here."""
    strings = {}
    for line in rc_path.read_text(encoding="utf-8").split("\n"):
        m = re.match(r'\s*(\d+),\s*"(.*)"\s*$', line)
        if m:
            s = m.group(2).replace('\\"', '"')
            s = re.sub(r"\\x([0-9A-Fa-f]{2})", lambda x: chr(int(x.group(1), 16)), s)
            strings[int(m.group(1))] = s.replace("\\n", "\n").replace("\\t", "\t").replace("\\\\", "\\")
    blocks = {}
    for i, s in strings.items():
        blocks.setdefault(i // 16 + 1, {})[i % 16] = s

    def entry(typ, name, flags, payload):
        hdr = struct.pack("<HHHH", 0xFFFF, typ, 0xFFFF, name) + struct.pack("<IHHII", 0, flags, 0, 0, 0)
        e = struct.pack("<II", len(payload), 8 + len(hdr)) + hdr + payload
        return e + b"\0" * (-len(e) % 4)

    res = entry(0, 0, 0, b"")
    for blk, items in sorted(blocks.items()):
        data = b"".join(struct.pack("<H", len(items.get(i, ""))) + items.get(i, "").encode("utf-16-le")
                        for i in range(16))
        res += entry(6, blk, 0x1030, data)
    return res


def rh(exe, *args):
    with tempfile.TemporaryDirectory() as t:
        log = Path(t) / "rh.log"
        subprocess.run([exe, *args, "-log", str(log)])
        out = log.read_bytes().decode("utf-16-le", "replace") if log.exists() else ""
    if "Success!" not in out:
        raise SystemExit(f"Resource Hacker failed: {' '.join(args)}\n{out}")


def translate(exe, src, dst, deletes, rc=None, res_bytes=None):
    with tempfile.TemporaryDirectory() as t:
        t = Path(t)
        cur = src
        for i, mask in enumerate(deletes):
            nxt = t / f"step{i}{src.suffix}"
            rh(exe, "-open", str(cur), "-save", str(nxt), "-action", "delete", "-mask", mask)
            cur = nxt
        res = t / "fr.res"
        if rc is not None:
            rc16 = t / "fr.rc"
            rc16.write_text(rc.read_text(encoding="utf-8"), encoding="utf-16", newline="\r\n")
            rh(exe, "-open", str(rc16), "-save", str(res), "-action", "compile")
        else:
            res.write_bytes(res_bytes)
        rh(exe, "-open", str(cur), "-save", str(dst), "-action", "addoverwrite", "-res", str(res))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rh", default=r"C:\Program Files (x86)\Resource Hacker\ResourceHacker.exe")
    exe = ap.parse_args().rh
    build_core_ini()
    build_regs()
    translate(exe, JUMPER / "KERNELEX.DLL", HERE / "KernelEx-fr.dll", ["STRINGTABLE,,1033"],
              res_bytes=string_table_res(SRC / "kernelex_fr.rc"))
    translate(exe, JUMPER / "SHEET.DLL", HERE / "sheet-fr.dll",
              ["DIALOG,,1033", "STRINGTABLE,,1033"], rc=SRC / "sheet_fr.rc")
    translate(exe, JUMPER / "VERIFY.EXE", HERE / "verify-fr.exe",
              ["DIALOG,,1033", "STRINGTABLE,,1033"], rc=SRC / "verify_fr.rc")
    print("OK : core.ini, kexmaj.reg, api-ms-w.reg, KernelEx-fr.dll, sheet-fr.dll, verify-fr.exe")


if __name__ == "__main__":
    main()
